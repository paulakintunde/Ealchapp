export const RYTHME_IDS: string[] = RYTHME.map((r) => r.id);

/** The ids that ALREADY EXIST and are being updated, not created. A dry run
 *  that does not report exactly this many updates has re-authored the corpus. */
export const EXISTING_IDS: string[] = RYTHME_IDS.slice(0, 165);

/** The ids authored by this build. */
export const NEW_IDS: string[] = RYTHME_IDS.slice(165);

/** The eight same-words-different-grouping pairs, as [a, b] tuples. The whole
 *  argument for the lesson lives here: identical words, different meaning. */
export const MINIMAL_PAIRS: [RythmeRow, RythmeRow][] = (() => {
  const byTag = new Map<string, RythmeRow[]>();
  for (const r of RYTHME) {
    const t = r.tags.find((x) => x.startsWith('pair-'));
    if (t) byTag.set(t, [...(byTag.get(t) ?? []), r]);
  }
  return [...byTag.values()].map((v) => [v[0], v[1]] as [RythmeRow, RythmeRow]);
})();

/** The most syllables BeatRow can draw in one row and stay legible.
 *
 *  MEASURED on a Pixel 6 (411dp wide, 363dp usable inside the page padding),
 *  not chosen: at 9 syllables the chip is 35dp and every label reads; at 10 it
 *  is 30dp and labels overflow their chips. Lives here rather than in
 *  BeatRow.tsx so the guard test can import it without pulling a .tsx module
 *  into the node test runner, which cannot load one. BeatRow re-exports it. */
export const MAX_BEATS_PER_GROUP = 9;

/** Items whose every group fits a legible beat row (<= MAX_BEATS_PER_GROUP). */
export const TAPPABLE: RythmeRow[] = RYTHME.filter((r) => r.tags.includes('tappable'));

/** Look-up by id, for the lesson body to read fr/ipa/respell from ONE place
 *  rather than restating them on every card that shows the sentence. */
export const BY_ID: Record<string, RythmeRow> = Object.fromEntries(
  RYTHME.map((r) => [r.id, r])
);

/** Syllables of an IPA string, splitting on spaces, dots and the phrase mark.
 *  Exported because the guard test recomputes it rather than trusting `syll`. */
export function syllablesOf(ipa: string): string[] {
  return ipa.trim().split(/[ .|]+/u).filter(Boolean);
}

/** The rhythm groups of an IPA string: one per phrase-break-delimited span. */
export function groupsOf(ipa: string): string[][] {
  return ipa.split('|').map((g) => g.trim().split(/[ .]+/u).filter(Boolean));
}
