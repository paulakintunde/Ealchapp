function pourTonCompteRendu(id: string, frSub: string, groups: SoundGroup[], terms: string[]): Sec<'groupDrill'> {
  return {
    type: 'groupDrill', id, layer: 'core', size: 'lg', title: 'Pour ton compte rendu', frSub,
    groups, audio: AUDIO, say: REFRAME, terms,
  };
}

