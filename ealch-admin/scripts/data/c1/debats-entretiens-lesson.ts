/** MissionRich renders authored order, so every closed mission item (group
 *  checks, listening questions, trap drills, remediation mcqs) must be
 *  spread by hand (playbook 6.11; scripts/b1-answer-slots.test.ts). This
 *  ROTATES each item's options with its `correct` index onto the least-used
 *  slot of its option-count class, never making three identical answers in
 *  a row, in the test's own walk order. No text changes, and no `why` names
 *  a slot. The quiz is excluded (LessonRich reshuffles it; spreadSlots
 *  below handles its authored order). */
function spreadMissions(sections: LessonSection[], drills: LessonDrill[]): void {
  const used: Record<number, number[]> = {};
  const last: number[] = [];
  const visit = (n: any): void => {
    if (!n || typeof n !== 'object') return;
    if (Array.isArray(n)) { n.forEach(visit); return; }
    if (typeof n.correct === 'number' && Array.isArray(n.opts)) {
      const k = n.opts.length as number;
      const u = (used[k] ??= new Array(k).fill(0));
      const runOf = (slot: number) => last.length >= 2 && last[last.length - 1] === slot && last[last.length - 2] === slot;
      let target = -1;
      for (let s = 0; s < k; s++) {
        if (runOf(s)) continue;
        if (target < 0 || u[s] < u[target] || (u[s] === u[target] && s === n.correct)) target = s;
      }
      const shift = (target - n.correct + k) % k;
      const opts = n.opts.slice();
      n.opts = opts.map((_: string, i: number) => opts[(i - shift + k) % k]);
      n.correct = target;
      u[target]++;
      last.push(target);
    }
    Object.values(n).forEach(visit);
  };
  for (const s of sections) if (s.type !== 'quiz') visit(s);
  for (const d of drills) visit(d);
}
