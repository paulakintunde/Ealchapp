const BY_ID: Map<string, BnRow> = new Map(BEAU_NOUVEAU.map((r) => [r.id, r]));

function must(id: string): BnRow {
  const r = BY_ID.get(id);
  if (!r) throw new Error(`beau-nouveau-corpus: no authored row ${id}`);
  return r;
}

export function toItem(r: BnRow): Item {
  const { role, adj, form: f, ...rest } = r;
  void role; void adj; void f;
  return rest as Item;
}

export const fr = (id: string): string => must(id).fr;
export const en = (id: string): string => must(id).en ?? '';
export const bare = (id: string): string => must(id).respell ?? '';
export const sub = (id: string): string => `[${bare(id)}]`;
export const noStop = (s: string): string => s.replace(/\.$/, '');

/** The adjective alone, off the GRID constant rather than off a sentence, so
 *  the two copies can be compared instead of one being derived from the other.
 *  Declared as a function so the ADVERB_STEMS block above can call it. */
export function form(adj: Adj, f: Form): string {
  const row = GRID.find((r) => r.form === f);
  if (!row) throw new Error(`beau-nouveau-corpus: no grid form ${f}`);
  return row.forms[adj];
}
export function formRespell(adj: Adj, f: Form): string {
  const row = GRID.find((r) => r.form === f);
  if (!row) throw new Error(`beau-nouveau-corpus: no grid form ${f}`);
  return row.respells[adj];
}

/** The authored row for one predicate cell. THROWS on `vowel`, which has no
 *  predicate cell and never can: `Il est bel` is not French. That throw is the
 *  masculine-only constraint enforced in the type system's absence. */
export const cellId = (adj: Adj, f: Exclude<Form, 'vowel'>): string => {
  const r = GRID_ROWS.find((x) => x.adj === adj && x.form === f);
  if (!r) throw new Error(`beau-nouveau-corpus: no grid row for ${adj}/${f}`);
  return r.id;
};
