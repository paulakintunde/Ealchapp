/** MEET THE TEXT: the act's anchor reading. */
function lecture(
  id: string, title: string, frSub: string, text: string,
  glossary: { word: string; en: string; note?: string }[], questions: RQ[], rec: string, terms: string[],
): Sec<'reading'> {
  return {
    type: 'reading', id, layer: 'core', questionsInModal: true, title, frSub, text,
    ...(glossary.length ? { glossary } : {}), questions,
    audio: REC(rec), say: REFRAME, terms,
  };
}

/** USE IT: the act's one tool for the task. Always the same title. Items are
 *  natural French only; the calque lives in the check's options. */
function pourTaTraduction(id: string, frSub: string, groups: SoundGroup[], terms: string[]): Sec<'groupDrill'> {
  return {
    type: 'groupDrill', id, layer: 'core', size: 'lg', title: 'Pour ta traduction', frSub,
    groups, audio: AUDIO, say: REFRAME, terms,
  };
}

/** IN A TEXT: the 60 to 120 word draft that closes acts 3 to 11, to
 *  correct, answers behind the modal. Always the same title. */
function texteAReprendre(id: string, frSub: string, text: string, questions: RQ[], rec: string, terms: string[]): Sec<'reading'> {
  return {
    type: 'reading', id, layer: 'core', questionsInModal: true,
    title: 'Un texte à reprendre', frSub, text, questions,
    audio: REC(rec), say: REFRAME, terms,
  };
}

/** The act check: control pages only, gated, before the checkpoint. */
function actCheck(id: string, title: string, groups: SoundGroup[], terms: string[]): Sec<'groupDrill'> {
  return {
    type: 'groupDrill', id, layer: 'core', size: 'lg', title, frSub: 'Le point avant la pause',
    groups, audio: AUDIO, say: `Petit bilan. ${REFRAME}`, terms,
  };
}

