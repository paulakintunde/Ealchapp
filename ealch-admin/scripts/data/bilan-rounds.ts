// a1.30.l1 "Bilan A1": the twenty-nine review rounds.
//
// One round per A1 lesson, five questions each, in the band's own teaching
// order (the unit `seq`, not the id: a1.27 and a1.28 sit third and fourth
// because that is where the numbers lesson chain actually runs).
//
// ══════════════════════════════════════════════════════════════════════════
//  WHY ONE ROUND PER LESSON, AND WHY THAT IS NOT THE WHOLE BILAN
// ══════════════════════════════════════════════════════════════════════════
//
// A round that names its lesson is a DIAGNOSTIC. Miss three of five in
// "Partitive articles" and the report says which half hour to sit again. That
// is what the shipped v1 bilan could not do: it grouped its fifteen rounds by
// pairs of lessons, so a failed round named two candidates and the learner had
// to guess which.
//
// The cost of naming the lesson is that the question stops testing retrieval.
// Told the round is about avoir, nobody reaches for être. That is why the
// sixty-question exam is a SEPARATE lesson (a1.30.l2) whose rounds are
// deliberately unlabelled by source: the review tells you where you are, the
// exam tells you whether you have it. Neither does the other's job and running
// them in one sitting was the thing worth splitting.
//
// ── On `ref` ───────────────────────────────────────────────────────────────
//
// Every question carries one because the density validator requires it, but
// `onJumpToRef` resolves a section id inside THIS lesson and the teaching for
// these questions lives in twenty-nine others. There is no cross-lesson jump
// in the pager, so the ref self-points at the quiz section and the actual
// pointer is carried in `why`, which names the lesson in words. A jump that
// silently lands nowhere would be worse than no jump.
//
// ── On the format mix ──────────────────────────────────────────────────────
//
// Five questions, and never five of one shape. Each round runs a recognition
// question, a production question and at least one of listenChoose or speak,
// because a learner who can only pick the right answer off a list of four has
// not finished the lesson. `listenChoose` ALWAYS carries `audio.clip`: the card
// falls back to speaking the correct option when the clip is missing, which
// reads the answer aloud before the learner has chosen.

